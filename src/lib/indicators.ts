export function getIndicator(id: IndicatorId): IndicatorDef {
  return INDICATORS.find((i) => i.id === id)!
}

export function systemOf(id: IndicatorId): SystemDef {
  return SYSTEMS.find((s) => s.indicators.includes(id))!
}

export function fmt(id: IndicatorId, v: number): string {
  return v.toFixed(getIndicator(id).decimals)
}
